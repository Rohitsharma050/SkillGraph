import mongoose from "mongoose";

// ---- Sub-schema: Node ----
const nodeSchema = new mongoose.Schema(
    {
        id: { type: String, required: true },
        label: { type: String, required: true },
        type: { type: String }, // 'existing' | 'missing'
        level: { type: Number }, // graph depth used for visual layout
        proficiency: {
            type: Number,
            min: 0,
            max: 3,
            default: 0,
        },
        targetProficiency: {
            type: Number,
            min: 1,
            max: 3,
            default: 3,
        },
        totalHours: {
            type: Number,
            default: 0,
        },
        remainingHours: {
            type: Number,
            default: 0,
        },
        hoursSource: {
            type: String,
            enum: ["resources", "default"],
            default: "default",
        },
        status: {
            type: String,
            enum: ["completed", "in_progress", "available", "locked"],
            default: "available",
        },
        description: { type: String },
    },
    { _id: false }
);

// ---- Sub-schema: Edge ----
const edgeSchema = new mongoose.Schema(
    {
        from: { type: String, required: true },
        to: { type: String, required: true },
        relation: { type: String, default: "prerequisite" },
        minLevel: {
            type: Number,
            min: 1,
            max: 3,
            default: 1,
        },
    },
    { _id: false }
);

// ---- Sub-schema: Learning Step ----
const learningStepSchema = new mongoose.Schema(
    {
        order: { type: Number },
        skill: { type: String },
        reason: { type: String },
        estimatedTime: { type: String },
        resources: { type: [mongoose.Schema.Types.Mixed], default: [] },
    },
    { _id: false }
);

// ---- Main Roadmap Schema ----
const roadmapSchema = new mongoose.Schema(
    {
        userId: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "User",
            required: true,
        },
        title: {
            type: String,
            default: "",
        },
        targetRole: {
            type: String,
            required: true,
        },
        resumeUrl: {
            type: String,
            default: "",
        },
        extractedSkills: {
            type: [String],
            default: [],
        },
        missingSkills: {
            type: [String],
            default: [],
        },
        nodes: {
            type: [nodeSchema],
            default: [],
        },
        edges: {
            type: [edgeSchema],
            default: [],
        },
        learningSteps: {
            type: [learningStepSchema],
            default: [],
        },
        explanation: {
            type: String,
            default: "",
        },
        completedNodes: {
            type: [String],
            default: [],
        },
        progressPercentage: {
            type: Number,
            default: 0,
        },
        isArchived: {
            type: Boolean,
            default: false,
        },
        // AI-generated documentation for this roadmap.
        documentation: {
            content: { type: mongoose.Schema.Types.Mixed, default: null },
            generatedAt: { type: Date, default: null },
        },
        // ── Adaptive Study Planner Configuration & Results ──────────────────
        planSettings: {
            hoursPerWeek: { type: Number, default: 10 },
            startDate: { type: Date, default: Date.now },
            deadlineWeeks: { type: Number, default: 12 },
            maxParallelSkills: { type: Number, default: 2 },
        },
        // Cached week-by-week plan object generated by capacity-constrained scheduler
        plan: {
            type: mongoose.Schema.Types.Mixed,
            default: null,
        },
        // Learner speed factor based on ProgressLog (clamped to [0.5, 2.0], default 1.0)
        speedFactor: {
            type: Number,
            default: 1.0,
        },
    },
    { timestamps: true }
);

// ---- Indexes ----
roadmapSchema.index({ userId: 1 });
roadmapSchema.index({ targetRole: 1 });
roadmapSchema.index({ createdAt: -1 });

const roadmapModel = mongoose.model("Roadmap", roadmapSchema);
export default roadmapModel;
